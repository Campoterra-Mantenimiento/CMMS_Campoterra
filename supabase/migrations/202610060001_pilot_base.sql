-- Ejecutar UNA VEZ en campoterra-piloto, como postgres desde SQL Editor.
-- Base inicial: no importa MySQL ni habilita todavía el envío de reportes.
begin;

create schema campoterra_private;
revoke all on schema campoterra_private from public, anon, authenticated;
grant usage on schema campoterra_private to authenticated;

-- Una identidad Auth por encargado o dispositivo; NO una por técnico.
create table campoterra_private.accesos (
    auth_user_id uuid primary key references auth.users(id),
    tipo text not null check (tipo in ('encargado', 'dispositivo')),
    nombre text not null check (length(trim(nombre)) > 0),
    activo boolean not null default true,
    creado_en timestamptz not null default now()
);
alter table campoterra_private.accesos enable row level security;
revoke all on campoterra_private.accesos from public, anon, authenticated;

create function campoterra_private.tipo_acceso()
returns text language sql stable security definer set search_path = ''
as $$
    select a.tipo from campoterra_private.accesos a
    where a.auth_user_id = (select auth.uid()) and a.activo;
$$;
revoke all on function campoterra_private.tipo_acceso() from public, anon, authenticated;
grant execute on function campoterra_private.tipo_acceso() to authenticated;

create table public.tecnicos (
    id_tecnico integer generated by default as identity primary key,
    nombre varchar(100) not null check (length(trim(nombre)) > 0),
    estado varchar(50) not null default 'Activo' check (estado in ('Activo', 'Inactivo'))
);
create table public.turnos (
    id_turno integer generated by default as identity primary key,
    descripcion varchar(50) not null,
    hora_inicio time not null,
    hora_fin time not null
);
create table public.areas_mantenimiento (
    id_area integer generated by default as identity primary key,
    nombre varchar(100) not null unique,
    activa boolean not null default true
);
create table public.equipos (
    id_equipo integer generated by default as identity primary key,
    codigo_interno varchar(50) unique,
    nombre varchar(100) not null,
    area_ubicacion varchar(100),
    estado varchar(50) not null default 'Operativo',
    notas_adicionales varchar(255)
);
create table public.piezas (
    id_pieza integer generated by default as identity primary key,
    nombre varchar(100) not null,
    codigo varchar(50) not null unique,
    stock integer not null default 0 check (stock >= 0),
    categoria varchar(50) not null default 'General',
    icon varchar(50) not null default 'cog-outline'
);
create table public.bitacoras (
    id_bitacora integer generated by default as identity primary key,
    id_equipo integer references public.equipos,
    id_area integer not null references public.areas_mantenimiento,
    id_tecnico integer not null references public.tecnicos,
    id_turno integer not null references public.turnos,
    tipo_mantenimiento varchar(50) not null,
    descripcion text not null check (length(trim(descripcion)) > 0),
    detalles_repuestos text,
    -- Distinguir captura offline y recepción en el servidor.
    fecha_registro timestamptz not null,
    recibido_en timestamptz not null default now(),
    dispositivo_id uuid not null references campoterra_private.accesos(auth_user_id)
);
create table public.movimientos_piezas (
    id_movimiento integer generated by default as identity primary key,
    id_pieza integer not null references public.piezas,
    id_bitacora integer references public.bitacoras,
    tipo varchar(20) not null check (tipo in ('Entrada', 'Salida')),
    cantidad integer not null check (cantidad > 0),
    motivo varchar(255) not null,
    fecha_movimiento timestamptz not null default now()
);
create table campoterra_private.reportes_idempotencia (
    idempotency_key uuid primary key,
    dispositivo_id uuid not null references campoterra_private.accesos(auth_user_id),
    payload jsonb not null,
    response_folio integer not null references public.bitacoras,
    creado_en timestamptz not null default now()
);
alter table campoterra_private.reportes_idempotencia enable row level security;
revoke all on campoterra_private.reportes_idempotencia from public, anon, authenticated;

create table public.notificaciones (
    id_notificacion integer generated by default as identity primary key,
    tipo varchar(50) not null default 'informativa',
    titulo varchar(150) not null,
    mensaje text not null,
    fecha timestamptz not null default now(),
    leida boolean not null default false,
    enlace varchar(255),
    referencia_id integer references public.bitacoras
);

create index on public.bitacoras (id_tecnico, fecha_registro desc);
create index on public.bitacoras (dispositivo_id);
create index on public.movimientos_piezas (id_pieza, fecha_movimiento desc);
create index on public.notificaciones (leida, fecha desc);

-- Grants explícitos: funciona aunque se haya desactivado exposición automática.
-- Ningún visitante con solo la publishable key obtiene acceso.
do $$
declare t text;
begin
    foreach t in array array['tecnicos', 'turnos', 'areas_mantenimiento', 'equipos',
                             'piezas', 'bitacoras', 'movimientos_piezas', 'notificaciones']
    loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on public.%I from public, anon, authenticated', t);
        execute format('grant select on public.%I to authenticated', t);
        execute format('create policy encargado_lectura on public.%I for select to authenticated using ((select campoterra_private.tipo_acceso()) = %L)', t, 'encargado');
        execute format('revoke all on sequence public.%I from public, anon, authenticated',
            t || case t
                when 'tecnicos' then '_id_tecnico_seq'
                when 'turnos' then '_id_turno_seq'
                when 'areas_mantenimiento' then '_id_area_seq'
                when 'equipos' then '_id_equipo_seq'
                when 'piezas' then '_id_pieza_seq'
                when 'bitacoras' then '_id_bitacora_seq'
                when 'movimientos_piezas' then '_id_movimiento_seq'
                else '_id_notificacion_seq' end);
    end loop;
end;
$$;
grant usage on schema public to authenticated;

create policy dispositivo_lectura on public.tecnicos for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo' and estado = 'Activo');
create policy dispositivo_lectura on public.turnos for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo');
create policy dispositivo_lectura on public.areas_mantenimiento for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo' and activa);
create policy dispositivo_lectura on public.equipos for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo');
create policy dispositivo_lectura on public.piezas for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo');
create policy dispositivo_lectura on public.bitacoras for select to authenticated
using ((select campoterra_private.tipo_acceso()) = 'dispositivo'
       and dispositivo_id = (select auth.uid()));

-- Las escrituras quedan cerradas hasta instalar las operaciones transaccionales.
-- Evita guardar reportes o cambiar stock por llamadas independientes.
commit;
